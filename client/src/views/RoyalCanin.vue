<script setup>
import { ref, onMounted, onUnmounted } from 'vue'

const current = ref(0)
let wrap = null

function onScroll() {
  current.value = Math.round(wrap.scrollTop / wrap.clientHeight)
}
function goTo(i) {
  wrap.scrollTo({ top: i * wrap.clientHeight, behavior: 'smooth' })
}

onMounted(() => {
  document.title = 'Royal Canin × NutriKer'
  document.body.style.overflow = 'hidden'
  wrap = document.querySelector('.rc-wrap')
  wrap.addEventListener('scroll', onScroll, { passive: true })
})
onUnmounted(() => {
  document.body.style.overflow = ''
  if (wrap) wrap.removeEventListener('scroll', onScroll)
})
</script>

